export const parseFlags = <Key extends string = string>(
  value: number | string,
  set: Record<Key, number | bigint>,
) => {
  const val = BigInt(value);
  const keys: Key[] = [];
  for (const [key, flag] of Object.entries(set)) {
    if ((BigInt(flag as number) & val) === val) {
      keys.push(key as Key);
    }
  }
  return keys;
};
